"""Original 16x16 pixel art for Jujutsu Craft items and blocks.

Writes:
  assets/jjkcraft/textures/item/<id>.png   (shard, trophies, spawn eggs)
  assets/jjkcraft/textures/block/<id>.png  (cursed root, gate barrier, curse nest)

Each item is a hand-drawn mask: one letter per pixel, '.' is transparent, and each letter maps to a
color in the item's palette. Spawn eggs share one egg mask and get speckles in the curse's colors.

Usage: python tools/gen_items.py src/main/resources/assets/jjkcraft
"""
import os
import random
import sys

from PIL import Image


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def shade(c, k):
    return tuple(max(0, min(255, int(v * k))) for v in c[:3]) + (255,)


def sprite(mask, palette):
    rows = [r for r in mask.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), mask
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                px[x, y] = palette[ch]
    return img


