def egg(curse, base, spots):
    b = rgb(base)
    s = rgb(spots)
    img = sprite(EGG, {"a": shade(b, 0.55), "b": b, "h": shade(b, 1.35) if sum(b[:3]) < 600 else shade(b, 1.05)})
    px = img.load()
    rnd = random.Random(sum(map(ord, curse)))
    placed = 0
    while placed < 9:
        x, y = rnd.randint(3, 12), rnd.randint(3, 13)
        if px[x, y] == b and px[x + 1, y] == b:
            px[x, y] = s
            if rnd.random() < 0.6:
                px[x + 1, y] = shade(s, 0.85)
            placed += 1
    return img


def noise_block(seed, base, dark, light, accent=None, veins=0, eye=False):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (16, 16), base)
    px = img.load()
    for y in range(16):
        for x in range(16):
            r = rnd.random()
            if r < 0.22:
                px[x, y] = dark
            elif r > 0.86:
                px[x, y] = light
    for _ in range(veins):
        x, y = rnd.randint(0, 15), rnd.randint(0, 15)
        for _ in range(rnd.randint(5, 10)):
            px[x % 16, y % 16] = accent
            x += rnd.choice((-1, 0, 1))
            y += rnd.choice((0, 1))
    if eye:
        for (x, y), c in {(6, 7): dark, (7, 6): dark, (8, 6): dark, (9, 7): dark, (6, 8): dark, (9, 8): dark, (7, 9): dark, (8, 9): dark,
                          (7, 7): accent, (8, 7): accent, (7, 8): accent, (8, 8): (20, 8, 24, 255)}.items():
            px[x, y] = c
    return img


def roots(seed):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (16, 16), rgb("#2A1410"))
    px = img.load()
    for _ in range(7):
        x = rnd.randint(0, 15)
        for y in range(16):
            for dx in (0, 1):
                px[(x + dx) % 16, y] = rgb("#7A2A24") if dx == 0 else rgb("#B8333F")
            x += rnd.choice((-1, 0, 0, 1))
    for _ in range(10):
        px[rnd.randint(0, 15), rnd.randint(0, 15)] = rgb("#E06A5A")
    return img


