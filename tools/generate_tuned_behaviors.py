"""Generate explicit typed copies: no reflective behavior mutation at cast time."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
folder=root/'src/main/java/com/jjkcraft/technique/behavior'
cases=[]; area=[]; durations=[]; reach=[]
for path in sorted(folder.glob('*Behavior.java')):
    m=re.search(r'public record (\w+)\((.*?)\)\s*implements TechniqueBehavior',path.read_text(),re.S)
    if not m: continue
    cls=m[1]; fields=[tuple(v.strip().split()) for v in m[2].split(',')]; args=[]
    for typ,name in fields:
        value=f'b.{name}()'
        if cls=='ProjectileBehavior' and name=='size':value='(float)Math.min(8,b.size()*a*t.details().expression().size()/100.0)'
        elif cls=='ProjectileBehavior' and name=='homingStrength':value='Math.min(1,b.homingStrength()*t.details().expression().steering()/100.0)'
        elif cls=='ProjectileBehavior' and name=='gravity':value='t.details().expression().gravity()<0?b.gravity():t.details().expression().gravity()/1000.0'
        elif cls=='SummonBehavior' and name=='count':value='t.details().expression().summons()==0?b.count():t.details().expression().summons()'
        elif cls=='BarrageBehavior' and name=='interval':value='t.details().expression().pulse()==0?b.interval():t.details().expression().pulse()'
        elif name in {'radius','strikeRadius','burstRadius','blastRadius','width','arc','size'}:
            area.append(cls);value=f'Math.min({360 if name=="arc" else 64}, {value}*a)'
            if typ=='float':value=f'(float){value}'
        elif name in {'distance','blink'}:reach.append(cls);value=f'Math.min(64,{value}*r)'
        elif name in {'duration','lifetime','selfTicks','otherTicks','regenTicks','burnSeconds','skipTicks','pullTicks'}:
            durations.append(cls);value=f'ticks({value},d{ "*r" if cls=="ProjectileBehavior" and name=="lifetime" else ""})'
        elif name=='invulnerableTicks':value=f'Math.min(20,ticks({value},p))'
        elif name in {'strength','knockback','launch'}:value=f'{value}*Math.sqrt(p)*t.details().force()/100.0'
        elif cls=='InfinityBehavior' and name=='slow':value=f'Math.pow({value},p)'
        elif cls=='InfinityBehavior' and name=='filter':value='t.mode()'
        elif cls=='BarrierBehavior' and name=='block':value=f'Math.min(0.95,{value}*Math.sqrt(p)*t.details().force()/100.0)'
        elif cls=='HealBehavior' and name=='cePerHealth':value=f'{value}*Math.sqrt(p)'
        elif cls=='ProjectileBehavior' and name=='speed':value=f'Math.min(8,{value}*t.details().speed()/100.0)'
        elif cls=='ProjectileBehavior' and name=='count':value=f't.details().shots()==0?{value}:t.details().shots()'
        elif cls=='ProjectileBehavior' and name=='spread':value=f't.details().spread()<0?{value}:t.details().spread()'
        elif cls=='ProjectileBehavior' and name=='homing':value=f't.details().homing()==0?{value}:t.details().homing()==2'
        elif cls=='ProjectileBehavior' and name=='pierce':value=f't.details().penetration()<0?{value}:t.details().penetration()>=50'
        elif cls=='LineCutBehavior' and name=='pierce':value=f't.details().penetration()<0?{value}:t.details().penetration()/100.0'
        args.append(value)
    cases.append(f'            case {cls} b -> new {cls}({",".join(args)});')
    if cls=='ProjectileBehavior':reach.append(cls)
def expr(items):return ' || '.join(f'b instanceof {c}' for c in sorted(set(items))) or 'false'
out='''package com.jjkcraft.technique;

import com.jjkcraft.technique.behavior.*;

/** Explicit copies keep active casts immutable and registry codecs untouched. Generated by tools/generate_tuned_behaviors.py. */
public final class TunedBehaviors {
    private TunedBehaviors() { }
    public static boolean output(TechniqueBehavior b) {
        return !(b instanceof MangaAbilityBehavior m && java.util.Set.of("body_transfer","swap").contains(m.ability()));
    }
    public static boolean area(TechniqueBehavior b) {
        if(b instanceof MangaAbilityBehavior m&&m.ability().startsWith("original/")&&(m.ability().endsWith("/step")||m.ability().endsWith("/guard")&&!m.ability().startsWith("original/ink/")&&!m.ability().startsWith("original/sand/")))return false;
        if(b instanceof MangaAbilityBehavior m && java.util.Set.of("body_transfer","curse_manipulation","swap","mass","armor","flowing_blood","flight").contains(m.ability()))return false;
        return AREA;
    }
    public static boolean duration(TechniqueDefinition definition) {
        TechniqueBehavior b=definition.behavior();
        if(b instanceof MangaAbilityBehavior m&&m.ability().startsWith("original/")&&m.ability().endsWith("/step"))return false;
        if(b instanceof MangaAbilityBehavior m && java.util.Set.of("body_transfer","curse_manipulation","uzumaki","swap","repel","blue_punch","red_punch","positive_output").contains(m.ability()))return false;
        return definition.cast().maxDuration()>0 || DURATION;
    }
    public static boolean reach(TechniqueDefinition definition) {
        TechniqueBehavior b=definition.behavior();return definition.cast().range()>0 || REACH;
    }
    private static int ticks(int base,double factor){return Math.max(base==0?0:1,Math.min(36000,(int)Math.round(base*factor)));}
    public static TechniqueBehavior apply(TechniqueBehavior behavior,TechniqueTuning t) {
        double p=t.output()/100.0,r=t.reach()/100.0,a=t.area()/100.0,d=t.duration()/100.0;
        return switch(behavior) {
CASES
            default -> behavior;
        };
    }
}
'''.replace('AREA',expr(area)).replace('DURATION',expr(durations)).replace('REACH',expr(reach)).replace('CASES','\n'.join(cases))
(root/'src/main/java/com/jjkcraft/technique/TunedBehaviors.java').write_text(out)
